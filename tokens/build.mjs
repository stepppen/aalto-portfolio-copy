// Compiles DTCG tokens to CSS custom properties.
//
//   primitives.json → semantic.json → :root { --bg, --ink, --signal, … }
//
// Primitives are never emitted: components can only see semantic tokens.
// This is the same pipeline I use at work, at the size of a portfolio.
import StyleDictionary from 'style-dictionary'
import { writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))

const sd = new StyleDictionary({
  source: [here('./primitives.json'), here('./semantic.json')],
  log: { verbosity: 'silent', warnings: 'disabled' },
  platforms: { css: { transforms: ['name/kebab'], files: [] } },
})
const tokens = (await sd.getPlatformTokens('css')).allTokens.filter((t) => t.filePath.endsWith('semantic.json'))

const css = `/* Generated by tokens/build.mjs. Do not edit; change tokens/*.json instead. */\n:root {\n${tokens.map((t) => `  --${t.name}: ${t.$value};`).join('\n')}\n  color-scheme: light;\n}\n`
await mkdir(here('../app/assets/css'), { recursive: true })
await writeFile(here('../app/assets/css/tokens.css'), css)
await writeFile(here('./dist.json'), JSON.stringify(Object.fromEntries(tokens.map((t) => [t.name, t.$value])), null, 2) + '\n')
console.log(`tokens → app/assets/css/tokens.css (${tokens.length} semantic tokens)`)
